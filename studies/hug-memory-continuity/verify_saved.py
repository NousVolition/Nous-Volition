"""Recheck the published trajectories and audit without rerunning the solver.

Full spatial refinement trajectories are regenerated by run.py; their published
comparison summaries are not a substitute for those trajectories.
"""
import hashlib,json
from pathlib import Path
import numpy as np
from model import Hug,protocol,rows

ROOT=Path(__file__).resolve().parent

def main():
    p=protocol();r=json.loads((ROOT/'results.json').read_text());m=Hug(p,32)
    d=np.load(ROOT/'plot_data.npz',allow_pickle=False);t=d['time'];z=d['mechanics'];a=d['accumulators']
    assert len(t)==3853 and z.shape==(len(t),54,4)
    assert np.all(np.diff(t)>0) and t[-1]==p['horizon_s']
    assert all(np.isfinite(d[k]).all() for k in d.files if k!='repeat')
    assert [(x['scenario'],x['condition'],x['history']) for x in r['results']]==[(x['scenario'],x['condition'],x['history']) for x in rows(p)]
    prov=json.loads((ROOT/'run_provenance.json').read_text())
    for run in prov.values():
        for name,digest in run['source_hashes'].items():
            assert hashlib.sha256((ROOT/name).read_bytes()).hexdigest()==digest,name
        assert run['ledger_sha256']==hashlib.sha256((ROOT/'history_ledger.json').read_bytes()).hexdigest()
    expected=np.zeros((len(t),3))
    for e in p['events']:expected[:,e['channel']]+=np.clip(t-e['start_s'],0,e['end_s']-e['start_s'])*e['rate_per_s']
    for j,row in enumerate(m.rows):
        s=m.scenarios[row['scenario']];target=expected.copy()
        if s['erase']:target[t>=720]-=np.array([1,1,1])
        np.testing.assert_allclose(a[:,j],target,rtol=0,atol=1e-12)
    # Reconstruct the amplitude from displacement, independently of saved values.
    amp=np.stack([np.ptp(z[(t>=x-57)&(t<=x),:,0],axis=0)*m.Q*500 for x in t])
    np.testing.assert_allclose(amp,d['amplitude'],rtol=1e-12,atol=1e-12)
    baseline=np.median(amp[(t>=350)&(t<=450)],axis=0)
    ot=d['orbital_time'];idx=np.searchsorted(t,np.round(ot,10))
    np.testing.assert_allclose(t[idx],ot,rtol=0,atol=1e-9)
    delta=np.abs(z[idx[1:]]-z[idx[:-1]]).max(axis=2)
    repeat=np.full(d['repeat'].shape,np.nan)
    for i in range(10,len(ot)):repeat[i]=delta[i-10:i].max(axis=0)
    np.testing.assert_allclose(repeat,d['repeat'],rtol=1e-12,atol=1e-12,equal_nan=True)
    E=m.energy(z);w=d['work'];net=w[:,:,0]+w[:,:,1]+w[:,:,2]-w[:,:,3]-w[:,:,4]
    residual=np.abs(E-E[0]-net+net[0]).max(axis=0)
    np.testing.assert_allclose(residual,[x['energy_residual_scaled'] for x in r['results']],rtol=0,atol=1e-11)
    assert residual.max()<1e-5
    assert np.abs(d['fields']).max()<=m.bound() and d['field_rms'].max()<=m.bound()
    assert np.all(np.diff(w[:,:,3:],axis=0)>=-1e-10),'dissipation must not decrease'
    # Stored input and expressed field do not change with the external orbit.
    for s in range(9):
        np.testing.assert_allclose(a[:,s*6:s*6+6],np.repeat(a[:,s*6:s*6+1],6,axis=1),atol=1e-12)
        np.testing.assert_allclose(d['field_rms'][:,s*6:s*6+6],np.repeat(d['field_rms'][:,s*6:s*6+1],6,axis=1),atol=1e-12)
    # Before the deliberate reset, the two matched arms follow the same path.
    np.testing.assert_allclose(z[t<720,:6],z[t<720,6:12],rtol=0,atol=1e-11)
    def confirmation(time,ok,start):
        window=np.flatnonzero((time>=start)&(time<=949.5));bad=window[~ok[window]]
        k=window[0] if not len(bad) else bad[-1]+1
        return None if k>window[-1] else float(time[k]-720)
    for j,result in enumerate(r['results']):
        s=m.scenarios[result['scenario']]
        np.testing.assert_allclose(baseline[j],result['baseline_half_amplitude_mm'],atol=1e-12)
        amp_delay=confirmation(t,amp[:,j]>=.8*baseline[j],777) if s['pause'] else None
        rep_delay=confirmation(ot,repeat[:,j]<.01,782.7) if s['pause'] and result['condition'] else None
        assert amp_delay==result['amplitude_recovery_delay_s']
        assert rep_delay==result['mechanical_repeat_confirmation_delay_s']
    assert not p['ancestry_channel']['enabled'] and r['human_measurements']==r['physical_measurements']==0
    # The published refinement summaries preserve failures and finite differences.
    assert r['refinements']['fine']['paths']==54 and r['refinements']['spatial']['paths']==9
    assert r['refinements']['timefine']['max_scaled_mechanical_path_difference']<1e-5
    assert r['refinements']['spatial']['max_field_difference_to_64']<r['refinements']['spatial']['max_field_difference_to_main_cells']
    print(json.dumps(dict(passed=True,paths=54,saved_samples=len(t),maximum_energy_residual=float(residual.max()),verified='provenance, causal retained inputs, reset control, energy, bounds, amplitude, mechanical repetition and summaries'),indent=2))

if __name__=='__main__':main()
