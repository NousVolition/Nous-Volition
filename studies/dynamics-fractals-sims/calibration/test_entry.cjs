const assert=require('node:assert/strict');
const fs=require('node:fs');
const entry=require('./measurement_entry.js');
assert.equal(entry.number('','blank'),null);
assert.equal(entry.number('0','zero'),0);
assert.equal(entry.number('2e-3','scientific'),.002);
for(const v of ['NaN','Infinity','0x10','1abc','=SUM(A1:A2)',true])assert.throws(()=>entry.number(v,'bad'));
const header=fs.readFileSync(__dirname+'/measurement_template.csv','utf8');
assert.deepEqual(entry.parseRows(header),[]);
const rows=entry.parseRows(header+'0,0,1,,0,\n1,0,2,,0,\n');
assert.equal(rows[0].velocity_mm_s,null);
assert.deepEqual(entry.parseRows(entry.toCSV(rows)),rows);
assert.deepEqual(entry.parseRows(entry.toCSV(rows).replaceAll(',','\t')),rows);
assert.throws(()=>entry.parseRows('time,x\n0,1'));
assert.throws(()=>entry.parseRows(header+'0,1,2\n'));
const s=JSON.parse(fs.readFileSync(__dirname+'/blank_session.json','utf8'));
assert.deepEqual(entry.checkTrial(s.trials[0]),['Awaiting measurements']);
const t=structuredClone(s.trials[0]);t.initial={known:true,delayed_strain:0,viscous_strain:0,velocity_mm_s:0};t.samples=Array.from({length:12},(_,i)=>({time_s:i,force_N:0,displacement_mm:i*.01,velocity_mm_s:null,active_force_N:null,orbit_force_N:null}));
assert.deepEqual(entry.checkTrial(t),[]);
t.samples[2].time_s=1;assert(entry.checkTrial(t).some(x=>x.includes('strictly increasing')));
t.samples[2].time_s=2;t.kind='eccentric';t.role='validation';t.controller_delay_s=0;
assert(entry.checkTrial(t).some(x=>x.includes('orbit_force_N')));
t.samples.forEach(r=>r.orbit_force_N=0);assert.deepEqual(entry.checkTrial(t),[]);
t.role='fit';assert(entry.checkTrial(t).some(x=>x.includes('Reserve')));
t.role='validation';t.kind='autonomous';t.samples[0].force_N=.1;
assert(entry.checkTrial(t).some(x=>x.includes('Split off')));
t.samples[0].force_N=0;t.controller_delay_s=.2;
assert(entry.checkTrial(t).some(x=>x.includes('history')));
console.log('Measurement entry: conversion, missing values, units, timing, roles and force checks passed');
